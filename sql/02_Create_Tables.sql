USE DATABASE GEOPULSE_DB;

USE SCHEMA RAW_DATA;

CREATE TABLE RAW_GPS_STAGE(
  DEVICE_ID VARCHAR(50),
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  TIMESTAMP TIMESTAMP_NTZ
);

CREATE TABLE GPS_DATA
(
    DEVICE_ID VARCHAR(50),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    TIMESTAMP TIMESTAMP_NTZ,
    LOCATION GEOGRAPHY
);
